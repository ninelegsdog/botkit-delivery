def confirm_create(number: str, client: str, title: str) -> str:
    """Шаг подтверждения: что именно будет создано, до записи в базу."""
    return f"Создать заказ?\n📋 #{number}\n👤 {client}\n📝 {title}"


def order_created(number: str) -> str:
    """Подтверждение создания: номер созданного заказа."""
